"""Detailed, reproducible evaluation for the IoT cleaning pipeline.

Run from the repository root:
    python experiments_detailed.py

Uses only the Python standard library and the project's own labelled simulator.
Writes results/detailed_evaluation.md and results/detailed_evaluation.json.
"""
import json
import math
import statistics
import time
from pathlib import Path

from src import config as C
from src.core import CleaningPipeline, generate, stream_clean
from src.evaluate import detection_scores, recall_by_fault, value_rmse

SEEDS = (11, 12, 13)
METHODS = {
    "Range rules": ("range",),
    "Hampel": ("hampel",),
    "Stuck-at": ("stuck",),
    "Spatial consistency": ("spatial",),
    "Isolation Forest": ("iforest",),
    "Rules (range + stuck)": ("range", "stuck"),
    "Hybrid (all five)": CleaningPipeline.METHODS,
}
ABLATIONS = {
    "Hybrid (all five)": CleaningPipeline.METHODS,
    "Without range": ("hampel", "stuck", "spatial", "iforest"),
    "Without Hampel": ("range", "stuck", "spatial", "iforest"),
    "Without stuck-at": ("range", "hampel", "spatial", "iforest"),
    "Without spatial": ("range", "hampel", "stuck", "iforest"),
    "Without Isolation Forest": ("range", "hampel", "stuck", "spatial"),
}

def avg(xs):
    return sum(xs) / len(xs) if xs else 0.0

def sd(xs):
    return statistics.stdev(xs) if len(xs) > 1 else 0.0

def score_one(rows, cleaned, flags):
    det = detection_scores(rows, flags)
    rms = value_rmse(rows, cleaned)
    return {
        "precision": avg([x["precision"] for x in det]),
        "recall": avg([x["recall"] for x in det]),
        "f1": avg([x["f1"] for x in det]),
        "raw_rmse": avg([x["raw_rmse"] for x in rms]),
        "cleaned_rmse": avg([x["cleaned_rmse"] for x in rms]),
        "rmse_improvement_pct": avg([x["improvement_%"] for x in rms]),
        "per_channel": det,
        "per_channel_rmse": rms,
    }

def run():
    started = time.perf_counter()
    report = [
        "# Detailed model evaluation",
        "",
        "Generated by `python experiments_detailed.py` using the current standard-library compatibility implementation.",
        "Synthetic evaluation uses labelled injected faults and the simulator's known clean values.",
        "Missing-value detection is reported separately from non-missing anomaly precision/recall.",
        "",
        "## 1. Experimental setup",
        "",
        f"- Channels: {', '.join(C.CHANNELS)}",
        "- Default synthetic dataset: 8 motes × 7 days × 5-minute interval (2,016 time steps per mote; 16,128 mote-time rows).",
        f"- Seeds: {', '.join(map(str, SEEDS))}",
        "- Default injected fault rate: 8% per channel, with spike, stuck, bias, drift, sentinel and missing faults.",
        "- Isolation Forest: 200 trees; contamination 0.03; deterministic seed derived from global seed, mote and channel.",
        "- Detection metrics: precision, recall and F1 against non-missing fault labels.",
        "- Repair metric: RMSE before and after cleaning against the simulator's hidden clean signal.",
        "- All values below are recalculated by the current implementation when this script is run.",
        "",
        "## 2. Detection method comparison (mean ± standard deviation across seeds)",
        "",
        "| Method | Precision | Recall | F1 | Raw RMSE | Cleaned RMSE | RMSE improvement |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    all_results = {"seeds": list(SEEDS), "method_comparison": {}, "ablation": {}, "fault_recall": {}, "online_vs_batch": {}}
    for name, methods in METHODS.items():
        per_seed = []
        for seed in SEEDS:
            rows = generate(seed=seed)
            cleaned_rows, cleaned, flags, _ = CleaningPipeline(methods).run(rows)
            per_seed.append(score_one(cleaned_rows, cleaned, flags))
        keys = ("precision", "recall", "f1", "raw_rmse", "cleaned_rmse", "rmse_improvement_pct")
        aggregate = {k: {"mean": avg([x[k] for x in per_seed]), "sd": sd([x[k] for x in per_seed])} for k in keys}
        all_results["method_comparison"][name] = aggregate
        cells = [f'{aggregate[k]["mean"]:.3f} ± {aggregate[k]["sd"]:.3f}' for k in keys]
        report.append("| " + name + " | " + " | ".join(cells) + " |")
    report += ["", "## 3. Per-channel performance (hybrid, seed 11)", "",
               "| Channel | Precision | Recall | F1 | Raw RMSE | Cleaned RMSE | RMSE improvement |",
               "|---|---:|---:|---:|---:|---:|---:|"]
    rows = generate(seed=11)
    rr, cc, ff, _ = CleaningPipeline().run(rows)
    base = score_one(rr, cc, ff)
    for d, rm in zip(base["per_channel"], base["per_channel_rmse"]):
        report.append(f'| {d["channel"]} | {d["precision"]:.3f} | {d["recall"]:.3f} | {d["f1"]:.3f} | {rm["raw_rmse"]:.4f} | {rm["cleaned_rmse"]:.4f} | {rm["improvement_%"]:.2f}% |')
    report += ["", "## 4. Fault-type recall (hybrid, seed 11)", "",
               "| Fault type | Recall |", "|---|---:|"]
    fault_recall = recall_by_fault(rr, ff)
    all_results["fault_recall"] = {k: (v if math.isfinite(v) else None) for k, v in fault_recall.items()}
    for fault, value in fault_recall.items():
        report.append(f"| {fault} | {value:.3f} |" if math.isfinite(value) else f"| {fault} | n/a |")
    report += ["", "## 5. Leave-one-layer-out ablation (seed 11)", "",
               "| Configuration | Precision | Recall | F1 | RMSE improvement |",
               "|---|---:|---:|---:|---:|"]
    for name, methods in ABLATIONS.items():
        if name == "Hybrid (all five)":
            result = base
        else:
            a, b, c, d = CleaningPipeline(methods).run(rows)
            result = score_one(a, b, c)
        all_results["ablation"][name] = {k: result[k] for k in ("precision", "recall", "f1", "rmse_improvement_pct")}
        report.append(f'| {name} | {result["precision"]:.3f} | {result["recall"]:.3f} | {result["f1"]:.3f} | {result["rmse_improvement_pct"]:.2f}% |')
    report += ["", "## 6. Causal online versus offline batch (seed 11)", "",
               "| Channel | Online F1 | Batch F1 | Online flagged | Batch flagged |",
               "|---|---:|---:|---:|---:|"]
    online = stream_clean(rows)
    online_by = {ch: {"tp": 0, "fp": 0, "fn": 0, "flagged": 0} for ch in C.CHANNELS}
    labels = {(r["timestamp"], r["mote_id"]): r for r in rows}
    for r in online:
        ch = r["channel"]
        source = labels[(r["timestamp"], r["mote_id"])]
        truth = bool(source.get("fault_" + ch) and source.get("fault_" + ch) != "missing")
        pred = bool(r["flagged"] and r["raw"] is not None)
        online_by[ch]["tp"] += int(truth and pred)
        online_by[ch]["fp"] += int((not truth) and pred)
        online_by[ch]["fn"] += int(truth and (not pred))
        online_by[ch]["flagged"] += int(bool(r["flagged"]))
    batch_flags = ff
    for ch in C.CHANNELS:
        od = online_by[ch]
        op = od["tp"] / (od["tp"] + od["fp"]) if od["tp"] + od["fp"] else 0
        ore = od["tp"] / (od["tp"] + od["fn"]) if od["tp"] + od["fn"] else 0
        of1 = 2*op*ore/(op+ore) if op+ore else 0
        di = C.CHANNELS.index(ch)
        bd = base["per_channel"][di]
        all_results["online_vs_batch"][ch] = {"online_f1": of1, "batch_f1": bd["f1"], "online_flagged": od["flagged"], "batch_flagged": sum(batch_flags[ch])}
        report.append(f'| {ch} | {of1:.3f} | {bd["f1"]:.3f} | {od["flagged"]} | {sum(batch_flags[ch])} |')
    report += ["", "## 7. Missing-value and repair notes", "",
               "- Missing readings are excluded from non-missing fault precision/recall by the project's evaluation helper.",
               "- Missing values are counted separately in the pipeline summary and are imputed by the repair stage.",
               "- RMSE compares both raw and cleaned values with the simulator's hidden clean values.",
               "- RMSE improvement can be negative if cleaning makes a value worse; it must not be hidden or clipped.",
               "- The current implementation's long-gap fallback is a robust median in the core imputer; this experiment reports the behaviour actually implemented.",
               "",
               "## 8. Reproducibility and interpretation", "",
               "- This is a controlled synthetic benchmark. It measures the known injected fault patterns, not every possible real sensor fault.",
               "- Results are specific to the configuration in `src/config.py` and the listed random seeds.",
               "- The current pure-Python Isolation Forest is not numerically identical to scikit-learn's implementation.",
               "- Intel Lab real-data inspection is a separate qualitative test because that dataset has no complete point-level ground-truth labels.",
               "",
               f"Total elapsed time: {time.perf_counter() - started:.1f} seconds."]
    Path("results").mkdir(exist_ok=True)
    Path("results/detailed_evaluation.md").write_text("\n".join(report) + "\n", encoding="utf-8")
    Path("results/detailed_evaluation.json").write_text(json.dumps(all_results, indent=2, allow_nan=False), encoding="utf-8")
    print("\n".join(report))
    print("\nSaved results/detailed_evaluation.md and results/detailed_evaluation.json")

if __name__ == "__main__":
    run()
